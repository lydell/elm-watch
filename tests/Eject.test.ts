import * as childProcess from "child_process";
import * as path from "path";
import { describe, expect, test } from "vitest";

import elmWatchCli from "../src";
import { copyFixture } from "./FixtureCopies";
import {
  assertExitCode,
  clean,
  logDebug,
  MemoryWriteStream,
  readFile,
  SilentReadStream,
  stringSnapshotSerializer,
} from "./Helpers";

expect.addSnapshotSerializer(stringSnapshotSerializer);

async function runEject(
  fixture: string,
  expectedExitCode: number,
  args: Array<string> = [],
): Promise<{ dir: string; stdout: string; stderr: string }> {
  const dir = copyFixture("eject", fixture);

  const stdout = new MemoryWriteStream();
  const stderr = new MemoryWriteStream();

  const exitCode = await elmWatchCli(["eject", ...args], {
    cwd: dir,
    env: {},
    stdin: new SilentReadStream(),
    stdout,
    stderr,
    logDebug,
  });

  assertExitCode(
    expectedExitCode,
    exitCode,
    stdout.content,
    stderr.content,
    dir,
  );

  return { dir, stdout: clean(stdout.content), stderr: clean(stderr.content) };
}

async function ejectSuccess(
  fixture: string,
): Promise<{ stdout: string; entrypoint: string }> {
  const { dir, stdout, stderr } = await runEject(fixture, 0);
  expect(stderr).toBe("");
  const entrypointPath = path.join(dir, "elm-watch.mjs");
  // Make sure that the generated code is syntactically valid.
  childProcess.execFileSync("node", ["--check", entrypointPath]);
  return { stdout, entrypoint: readFile(entrypointPath) };
}

