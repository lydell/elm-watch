import * as childProcess from "child_process";
import * as fs from "fs";
import * as path from "path";
import { describe, expect, test } from "vitest";

import elmWatchCli from "../src/index.ts";
import { copyFixture } from "./FixtureCopies.ts";
import {
  assertExitCode,
  clean,
  logDebug,
  MemoryWriteStream,
  readFile,
  SilentReadStream,
  stringSnapshotSerializer,
} from "./Helpers.ts";

expect.addSnapshotSerializer(stringSnapshotSerializer);

type Language = "javascript" | "typescript";

async function runInit(
  fixture: string,
  expectedExitCode: number,
  args: Array<string>,
): Promise<{ dir: string; stdout: string; stderr: string }> {
  const dir = copyFixture("init-entrypoint", fixture);

  const stdout = new MemoryWriteStream();
  const stderr = new MemoryWriteStream();

  const exitCode = await elmWatchCli(["init", ...args], {
    cwd: dir,
    env: {},
    stdin: new SilentReadStream(),
    stdout,
    stderr,
    logDebug,
  });

  assertExitCode(
    expectedExitCode,
    exitCode,
    stdout.content,
    stderr.content,
    dir,
  );

  return { dir, stdout: clean(stdout.content), stderr: clean(stderr.content) };
}

async function initSuccess(
  fixture: string,
  {
    language = "javascript",
    // Relative to the fixture: Where elm-watch.json is.
    projectDir = ".",
  }: { language?: Language; projectDir?: string } = {},
): Promise<{ stdout: string; entrypoint: string }> {
  const { dir, stdout, stderr } = await runInit(fixture, 0, [`--${language}`]);
  expect(stderr).toBe("");
  const entrypointPath = path.join(
    dir,
    projectDir,
    language === "typescript" ? "elm-watch.mts" : "elm-watch.mjs",
  );
  // Make sure that the generated code is syntactically valid.
  childProcess.execFileSync("node", ["--check", entrypointPath]);
  // elm-watch.json is replaced by the new file.
  expect(fs.existsSync(path.join(dir, projectDir, "elm-watch.json"))).toBe(
    false,
  );
  return { stdout, entrypoint: readFile(entrypointPath) };
}

