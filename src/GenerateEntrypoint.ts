import * as path from "path";
import * as Codec from "tiny-decoders";

import type { ElmWatchJsonWithLegacyPostprocess } from "./ElmWatchJson";
import { isNonEmptyArray, NonEmptyArray } from "./NonEmptyArray";

export type EntrypointLanguage = "javascript" | "typescript";

export const ENTRYPOINT_NAMES: Record<EntrypointLanguage, string> = {
  javascript: "elm-watch.mjs",
  typescript: "elm-watch.mts",
};

// elm-watch 1 had `"postprocess": ["elm-watch-node", "postprocess.js"]`.
const ELM_WATCH_NODE_LEGACY = "elm-watch-node";

// Generates elm-watch.mjs (or elm-watch.mts) from the contents of an
// elm-watch.json, for using the JavaScript API.
export function generateEntrypoint(
  json: ElmWatchJsonWithLegacyPostprocess,
  language: EntrypointLanguage,
): string {
  const entrypointName = ENTRYPOINT_NAMES[language];
  const typescript = language === "typescript";

  const postprocess =
    json.postprocess === undefined
      ? undefined
      : generatePostprocess(json.postprocess, typescript);

  const typeImports =
    postprocess === undefined ? "type Target" : "type Postprocess, type Target";

  const targets = Object.entries(json.targets)
    .map(([name, target]) =>
      `
  {
    name: ${js(name)},
    inputs: ${jsArray(target.inputs)},
    output: ${js(target.output)},${
      postprocess === undefined
        ? ""
        : `\n    postprocess: postprocessFor(${js(name)}),`
    }
  },`.slice(1),
    )
    .join("\n");

  const extraOptions = [
    json.port === undefined ? undefined : `port: ${js(json.port)},`,
    json.serve === undefined ? undefined : `staticFilesDir: ${js(json.serve)},`,
    json.webSocketUrl === undefined
      ? undefined
      : `webSocketUrl: ${js(json.webSocketUrl.url.href)},`,
    json.allowedHosts === undefined
      ? undefined
      : `allowedHosts: ${jsArray(json.allowedHosts)},`,
  ]
    .filter((line) => line !== undefined)
    .map((line) => `\n  ${line}`)
    .join("");

  return `
${typescript ? "" : "// @ts-check\n"}// Generated by \`elm-watch init --${language}\`. It’s yours now – change it
// however you like!
// Documentation: https://lydell.github.io/elm-watch/javascript-api/
//
// Usage (target names are matched by substring, like the elm-watch command):
//
//     node --watch ${entrypointName} hot [target names...]
//     node ${entrypointName} make [--debug|--optimize] [target names...]

${[
  ...(postprocess?.nodeImports ?? []),
  `import { parseArgs } from "node:util";`,
]
  .sort(byModuleName)
  .join("\n")}
import { elmWatch${typescript ? `, ${typeImports}` : ""} } from "elm-watch";
${postprocess?.localImport ?? ""}
const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: {
    debug: { type: "boolean", default: false },
    optimize: { type: "boolean", default: false },
  },
});

const [runMode = "hot", ...targetNames] = positionals;

if (runMode !== "hot" && runMode !== "make") {
  console.error(\`Expected "hot" or "make", but got: \${runMode}\`);
  process.exit(1);
}

${
  typescript
    ? "const targets: Array<Target> = ["
    : `/** @type {Array<import("elm-watch").Target>} */\nconst targets = [`
}
${targets}
];

const enabledTargets = targets.filter(
  (target) =>
    targetNames.length === 0 ||
    targetNames.some((targetName) => target.name.includes(targetName)),
);

if (enabledTargets.length === 0) {
  console.error(
    \`No targets match: \${targetNames.join(", ")}\\n\\nAvailable targets:\\n\${targets.map((target) => target.name).join("\\n")}\`,
  );
  process.exit(1);
}

process.exitCode = await elmWatch({
  root: import.meta.dirname,
  runMode,
  compilationMode: values.optimize
    ? "optimize"
    : values.debug
      ? "debug"
      : "standard",
  targets: enabledTargets,${extraOptions}
});
${postprocess === undefined ? "" : `\n${postprocess.functionCode}`}`.trimStart();
}

function generatePostprocess(
  postprocessArray: NonEmptyArray<string>,
  typescript: boolean,
): {
  nodeImports: Array<string>;
  localImport?: string;
  functionCode: string;
} {
  const [command, ...args] = postprocessArray;

  const postprocessForSignature = typescript
    ? "function postprocessFor(targetName: string): Postprocess {"
    : `
/**
 * @param {string} targetName
 * @returns {import("elm-watch").Postprocess}
 */
function postprocessFor(targetName) {`.slice(1);

  if (command === ELM_WATCH_NODE_LEGACY && isNonEmptyArray(args)) {
    const [script, ...scriptArgs] = args;
    const importPath = toImportPath(script);
    return {
      nodeImports: [`import * as path from "node:path";`],
      localImport: `${
        typescript
          ? "// TypeScript might complain about this JavaScript import. Consider converting\n// it to TypeScript, using the new signature (see postprocessFor below).\n"
          : ""
      }import elmWatchNodePostprocess from ${js(importPath)};\n`,
      functionCode: `
// Calls your postprocess function from elm-watch 1 (\`elm-watch-node\`), which
// took a single object with the code, target name, compilation mode, run mode
// and \`argv\`. Consider changing it to the new signature instead:
// https://lydell.github.io/elm-watch/postprocess/
${postprocessForSignature}
  return (code, { compilationMode, runMode }) =>
    elmWatchNodePostprocess({
      code,
      targetName,
      compilationMode,
      runMode,
      argv: [
        ${js(ELM_WATCH_NODE_LEGACY)},
        path.join(import.meta.dirname, ${js(script)}),${scriptArgs.map((arg) => `\n        ${js(arg)},`).join("")}
      ],
    });
}
`.trimStart(),
    };
  }

  return {
    nodeImports: [`import { spawn } from "node:child_process";`],
    functionCode: `
// Runs your postprocess command from elm-watch.json, like elm-watch 1 did:
// The code is written to stdin, and the result is read from stdout.
// Consider rewriting it as a JavaScript function instead:
// https://lydell.github.io/elm-watch/postprocess/
${postprocessForSignature}
  return (code, { compilationMode, runMode }) =>
    new Promise((resolve, reject) => {
      const child = spawn(
        ${js(command)},
        [${args.map((arg) => `${js(arg)}, `).join("")}targetName, compilationMode, runMode],
        { cwd: import.meta.dirname },
      );
      ${typescript ? "const stdout: Array<Buffer> = [];" : "/** @type {Array<Buffer>} */\n      const stdout = [];"}
      ${typescript ? "const stderr: Array<Buffer> = [];" : "/** @type {Array<Buffer>} */\n      const stderr = [];"}
      child.stdout.on("data", (chunk) => stdout.push(chunk));
      child.stderr.on("data", (chunk) => stderr.push(chunk));
      child.stdin.on("error", () => {
        // The command might exit before reading all of stdin. The exit code
        // and output tell more.
      });
      child.on("error", reject);
      child.on("close", (exitCode) => {
        if (exitCode === 0) {
          resolve(Buffer.concat(stdout).toString("utf8"));
        } else {
          reject(
            new Error(
              \`The postprocess command exited with code \${exitCode}.\\n\\nSTDOUT:\\n\${Buffer.concat(stdout).toString("utf8")}\\n\\nSTDERR:\\n\${Buffer.concat(stderr).toString("utf8")}\`,
            ),
          );
        }
      });
      child.stdin.end(code);
    });
}
`.trimStart(),
  };
}

function toImportPath(script: string): string {
  const withSlashes = script.split(path.sep).join("/");
  return withSlashes.startsWith(".") || withSlashes.startsWith("/")
    ? withSlashes
    : `./${withSlashes}`;
}

function byModuleName(a: string, b: string): number {
  const moduleName = (importLine: string): string =>
    importLine.slice(importLine.indexOf(" from "));
  return moduleName(a).localeCompare(moduleName(b));
}

function jsArray(values: Array<string>): string {
  return `[${values.map(js).join(", ")}]`;
}

function js(value: unknown): string {
  return Codec.JSON.stringify(Codec.unknown, value);
}
