// @ts-check
import * as fs from "node:fs";
import * as path from "node:path";
import { parseArgs } from "node:util";
import { elmWatch } from "elm-watch";

// Usage:
//
//     node --watch elm-watch.mjs hot
//     node elm-watch.mjs make --optimize
const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: {
    debug: { type: "boolean", default: false },
    optimize: { type: "boolean", default: false },
  },
});

const [runMode = "hot"] = positionals;

if (runMode !== "hot" && runMode !== "make") {
  console.error(`Expected "hot" or "make", but got: ${runMode}`);
  process.exit(1);
}

const TRANSLATIONS_JSON = path.join(import.meta.dirname, "translations.json");
const TRANSLATIONS_ELM = path.join(
  import.meta.dirname,
  "generated",
  "Translations.elm",
);

/**
 * Generates `generated/Translations.elm` from `translations.json`.
 *
 * If generation fails, an Elm file with a deliberate type error is generated
 * instead. Elm then shows the error message (in the terminal and in the
 * browser), just like any other compilation error. That’s a neat way of
 * showing errors without printing to the terminal yourself, which would mess
 * up elm-watch’s output.
 */
function generate() {
  let code;
  try {
    code = generateTranslationsElm(
      JSON.parse(fs.readFileSync(TRANSLATIONS_JSON, "utf8")),
    );
  } catch (error) {
    code = generateErrorElm(
      `Failed to generate Translations.elm from translations.json:\n\n${error instanceof Error ? error.message : String(error)}`,
    );
  }
  // Only write if something changed, to avoid unnecessary recompilation.
  const previous = fs.existsSync(TRANSLATIONS_ELM)
    ? fs.readFileSync(TRANSLATIONS_ELM, "utf8")
    : undefined;
  if (code !== previous) {
    fs.mkdirSync(path.dirname(TRANSLATIONS_ELM), { recursive: true });
    fs.writeFileSync(TRANSLATIONS_ELM, code);
  }
}

/**
 * @param {unknown} json
 * @returns {string}
 */
function generateTranslationsElm(json) {
  if (typeof json !== "object" || json === null || Array.isArray(json)) {
    throw new Error("Expected an object with languages as keys.");
  }
  const entries = Object.entries(json);
  const [first] = entries;
  if (first === undefined) {
    throw new Error("Expected at least one language.");
  }
  const keys = Object.keys(first[1] ?? {}).sort();
  for (const [language, translations] of entries) {
    if (!/^[A-Z][A-Za-z0-9_]*$/.test(language)) {
      throw new Error(
        `Language names must start with an uppercase letter and contain only letters, digits and underscores: ${language}`,
      );
    }
    if (typeof translations !== "object" || translations === null) {
      throw new Error(`${language}: Expected an object.`);
    }
    const languageKeys = Object.keys(translations).sort();
    const missing = keys.filter((key) => !languageKeys.includes(key));
    const extra = languageKeys.filter((key) => !keys.includes(key));
    if (missing.length > 0 || extra.length > 0) {
      throw new Error(
        `${language}: All languages must have the same keys as ${first[0]}.\nMissing: ${missing.join(", ") || "(none)"}\nExtra: ${extra.join(", ") || "(none)"}`,
      );
    }
    for (const [key, value] of Object.entries(translations)) {
      if (!/^[a-z][A-Za-z0-9_]*$/.test(key)) {
        throw new Error(
          `${language}: Keys must start with a lowercase letter and contain only letters, digits and underscores: ${key}`,
        );
      }
      if (typeof value !== "string") {
        throw new Error(`${language}.${key}: Expected a string.`);
      }
    }
  }

  const languages = entries.map(([language]) => language);
  return `module Translations exposing (Language(..), Translations, defaultLanguage, languageName, languages, translations)

{-| GENERATED by elm-watch.mjs from translations.json. Do not edit!
-}


type Language
    = ${languages.join("\n    | ")}


type alias Translations =
    { ${keys.map((key) => `${key} : String`).join("\n    , ")}
    }


defaultLanguage : Language
defaultLanguage =
    ${first[0]}


languages : List Language
languages =
    [ ${languages.join(", ")} ]


languageName : Language -> String
languageName language =
    case language of
${languages.map((language) => `        ${language} ->\n            ${elmString(language)}`).join("\n\n")}


translations : Language -> Translations
translations language =
    case language of
${entries
  .map(
    ([language, translations]) =>
      `        ${language} ->\n            { ${keys
        .map((key) => `${key} = ${elmString(translations[key])}`)
        .join("\n            , ")}\n            }`,
  )
  .join("\n\n")}
`;
}

/**
 * @param {string} message
 * @returns {string}
 */
function generateErrorElm(message) {
  return `module Translations exposing (error)

{-| GENERATED by elm-watch.mjs. Do not edit!

There was an error generating this file. This is a deliberate type error to
show the error message below. Fix the error, and this file will be regenerated.

-}


error : ()
error =
    """
${message.replace(/\\/g, "\\\\").replace(/"""/g, '""\\"')}
"""
`;
}

/**
 * @param {string} string
 * @returns {string}
 */
function elmString(string) {
  return `"${string.replace(/[\\"\n\r\t]|\p{Cc}/gu, (char) => {
    switch (char) {
      case "\\":
        return "\\\\";
      case '"':
        return '\\"';
      case "\n":
        return "\\n";
      case "\r":
        return "\\r";
      case "\t":
        return "\\t";
      default:
        return `\\u{${char.codePointAt(0)?.toString(16).padStart(4, "0")}}`;
    }
  })}"`;
}

generate();

// In hot mode, regenerate when translations.json changes. elm-watch then
// notices that Translations.elm changed, and recompiles. (Watching the
// directory rather than the file itself, since many editors save files by
// replacing them, which stops watchers on the file itself.)
const watcher =
  runMode === "hot"
    ? fs.watch(import.meta.dirname, (_eventType, filename) => {
        if (filename === path.basename(TRANSLATIONS_JSON)) {
          generate();
        }
      })
    : undefined;

process.exitCode = await elmWatch({
  root: import.meta.dirname,
  runMode,
  compilationMode: values.optimize
    ? "optimize"
    : values.debug
      ? "debug"
      : "standard",
  staticFilesDir: ".",
  targets: [
    {
      type: "application",
      name: "Main",
      elmJson: "elm.json",
      inputs: ["src/Main.elm"],
      output: "build/main.js",
    },
  ],
});

watcher?.close();
