// @ts-check
import * as crypto from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import { parseArgs } from "node:util";
import { elmWatch } from "elm-watch";

// Usage:
//
//     node --watch-path=elm-watch.mjs --watch-path=public/assets elm-watch.mjs hot
//     node elm-watch.mjs make --optimize
//
// `--watch-path=public/assets` restarts this script when an asset is added,
// removed or changed, which regenerates Assets.elm. Note that `--watch-path`
// turns off the default `--watch` behavior of watching the script itself, so
// we need `--watch-path=elm-watch.mjs` too.
const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: {
    debug: { type: "boolean", default: false },
    optimize: { type: "boolean", default: false },
  },
});

const [runMode = "hot"] = positionals;

if (runMode !== "hot" && runMode !== "make") {
  console.error(`Expected "hot" or "make", but got: ${runMode}`);
  process.exit(1);
}

const PUBLIC = path.join(import.meta.dirname, "public");
const ASSETS_ELM = path.join(import.meta.dirname, "generated", "Assets.elm");

/**
 * Generates `generated/Assets.elm`, with one constant per file in
 * `public/assets/`. For example, `public/assets/icons/star-filled.svg` becomes:
 *
 *     iconsStarFilled : String
 *     iconsStarFilled =
 *         "/assets/icons/star-filled.svg?v=1a2b3c4d"
 *
 * The `?v=` part is a hash of the file contents. When an image changes, its
 * URL changes, so the browser fetches the new version (cache busting). This
 * also means that changing an image makes Elm hot reload with the new image!
 *
 * @returns {string}
 */
function generateAssetsElm() {
  const files = fs
    // Built-in globs in Node.js! (Use forward slashes in globs, also on Windows.)
    .globSync("assets/**/*.{svg,png,jpg,jpeg,gif,webp}", { cwd: PUBLIC })
    .map((file) => file.split(path.sep).join("/"))
    .sort();

  if (files.length === 0) {
    throw new Error("No assets found in public/assets/.");
  }

  /** @type {Map<string, string>} */
  const names = new Map();
  const definitions = files.map((file) => {
    const name = elmName(file.replace(/^assets\//, ""));
    const existing = names.get(name);
    if (existing !== undefined) {
      throw new Error(`Both ${existing} and ${file} become: ${name}`);
    }
    names.set(name, file);
    const hash = crypto
      .createHash("sha256")
      .update(fs.readFileSync(path.join(PUBLIC, file)))
      .digest("hex")
      .slice(0, 8);
    return `${name} : String\n${name} =\n    "/${file}?v=${hash}"`;
  });

  return `module Assets exposing (${[...names.keys()].sort().join(", ")})

{-| GENERATED by elm-watch.mjs from the files in public/assets/. Do not edit!
-}


${definitions.join("\n\n\n")}
`;
}

/**
 * `icons/star-filled.svg` -> `iconsStarFilled`
 *
 * @param {string} file
 * @returns {string}
 */
function elmName(file) {
  const words = file
    .replace(/\.[^.]+$/, "")
    .split(/[^a-zA-Z0-9]+/)
    .filter((word) => word !== "");
  const name = words
    .map((word, index) =>
      index === 0
        ? word.charAt(0).toLowerCase() + word.slice(1)
        : word.charAt(0).toUpperCase() + word.slice(1),
    )
    .join("");
  return /^[a-z]/.test(name) ? name : `asset${name}`;
}

/**
 * If generation fails, generate an Elm file with a deliberate type error that
 * contains the error message, so that it shows up like any other Elm error
 * (in the terminal and in the browser).
 *
 * @param {string} message
 * @returns {string}
 */
function generateErrorElm(message) {
  return `module Assets exposing (error)

{-| GENERATED by elm-watch.mjs. Do not edit!

There was an error generating this file. This is a deliberate type error to
show the error message below. Fix the error, and this file will be regenerated.

-}


error : ()
error =
    """
${message.replace(/\\/g, "\\\\").replace(/"""/g, '""\\"')}
"""
`;
}

let code;
try {
  code = generateAssetsElm();
} catch (error) {
  code = generateErrorElm(
    `Failed to generate Assets.elm:\n\n${error instanceof Error ? error.message : String(error)}`,
  );
}
// Only write if something changed, to avoid unnecessary recompilation.
if (
  !fs.existsSync(ASSETS_ELM) ||
  fs.readFileSync(ASSETS_ELM, "utf8") !== code
) {
  fs.mkdirSync(path.dirname(ASSETS_ELM), { recursive: true });
  fs.writeFileSync(ASSETS_ELM, code);
}

process.exitCode = await elmWatch({
  root: import.meta.dirname,
  runMode,
  compilationMode: values.optimize
    ? "optimize"
    : values.debug
      ? "debug"
      : "standard",
  staticFilesDir: "public",
  targets: [
    {
      type: "application",
      name: "Main",
      elmJson: "elm.json",
      inputs: ["src/Main.elm"],
      output: "public/build/main.js",
    },
  ],
});
